// Bundles the campaign calculation for the browser. The output is committed so local
// runs and tests need no build step; tests/campaign-calc.test.ts fails if it is stale.
import { build } from 'esbuild';
import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root=path.dirname(path.dirname(fileURLToPath(import.meta.url)));
export const output=path.join(root,'epic3/web/campaign-calc.js');
export async function bundle(){
  const result=await build({entryPoints:[path.join(root,'lib/domain/campaign-browser.ts')],bundle:true,write:false,format:'iife',
    platform:'browser',target:'es2022',minify:true,legalComments:'none',
    plugins:[{name:'browser-catalogs',setup(b){b.onResolve({filter:/^\.\/catalogs$/},()=>({path:path.join(root,'lib/domain/catalogs.browser.ts')}));}}]});
  return '// Generated by scripts/build-campaign-calc.mjs from lib/domain/campaigns.ts; do not edit.\n'+result.outputFiles[0].text;
}
if(process.argv[1]===fileURLToPath(import.meta.url)){
  const script=await bundle();await writeFile(output,script);
  console.log('Built campaign calculator ('+Buffer.byteLength(script)+' bytes).');
}
